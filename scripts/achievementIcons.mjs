// Renders the Achievement Badges art from scripts/iconPaths.mjs to
// 64 px white WebP images: every name the plugin's badges, quests, tiers and cosmetics can carry goes to
// public/icons/ach, and src/ui/components/settings/social/achNames.js
// lists them so a name nothing knows falls back to the trophy. It also renders the settings glyphs
// the friends and achievement rows name in JSX, which scripts/settingsIcons.mjs doesn't list.
import { readFileSync, writeFileSync, mkdirSync, existsSync } from 'node:fs'
import { execFileSync } from 'node:child_process'
import { join } from 'node:path'
import { fileURLToPath } from 'node:url'
import { ACHIEVEMENT as achievement, MATERIAL_NAMES as nameMap, MATERIAL_SYMBOLS } from './iconPaths.mjs'

const pathsIn = (text) => {
  const out = {}
  for (const m of text.matchAll(/^\s+([a-zA-Z_0-9]+):\s*'([Mm][^']+)'/gm)) out[m[1]] = m[2]
  return out
}
const srcText = (file) => readFileSync(new URL(`../src/${file}`, import.meta.url), 'utf8')
const homeText = srcText('components/icons/homeIconPaths.js')
const homeMaterial = homeText.slice(homeText.indexOf('HOME_MATERIAL_ICON_PATHS'))
const material = { ...pathsIn(homeMaterial.slice(0, homeMaterial.indexOf('\n};'))), ...MATERIAL_SYMBOLS }
const core = pathsIn(srcText('views/Settings/settingsCoreIcons.js'))

const force = process.argv[2] === '--force'
const render = (file, svg) => {
  if (existsSync(file) && !force) return 0
  writeFileSync(file, execFileSync('magick', ['-background', 'none', '-density', '384', 'svg:-', '-resize', '64x64', '-define', 'webp:lossless=true', '-define', 'webp:exact=true', '-define', 'webp:method=6', 'webp:-'], { input: svg }))
  return 1
}
const big = (d) => `<svg xmlns="http://www.w3.org/2000/svg" width="64" height="64" viewBox="0 -960 960 960"><path fill="#ffffff" d="${d}"/></svg>`

const achDir = fileURLToPath(new URL('../public/icons/ach/', import.meta.url))
mkdirSync(achDir, { recursive: true })
const names = [...new Set([...Object.keys(achievement), ...Object.keys(material)])].sort()
let n = 0
for (const name of names) n += render(join(achDir, `${name}.webp`), big(achievement[name] || material[name]))
writeFileSync(
  new URL('../src/ui/components/settings/social/achNames.js', import.meta.url),
  `// Generated by scripts/achievementIcons.mjs: the badge art in public/icons/ach.\nexport const ACH_ICON_NAMES = ${JSON.stringify(names)}\n`
)

// The filled Core path in a 24 box, else the outlined symbol (by its mapped name).
const setDir = fileURLToPath(new URL('../public/icons/settings/', import.meta.url))
const GLYPHS = ['bolt', 'leaderboard', 'insights', 'backpack', 'face_5', 'storefront', 'pause_circle', 'casino', 'folder', 'folder_open']
let g = 0
for (const name of GLYPHS) {
  const svg = core[name]
    ? `<svg xmlns="http://www.w3.org/2000/svg" width="64" height="64" viewBox="0 0 24 24"><path fill="#ffffff" d="${core[name]}"/></svg>`
    : big(material[nameMap[name] || name] || material.settings)
  g += render(join(setDir, `${name}.webp`), svg)
}
console.log(`achievement icons: ${names.length} named, ${n} rendered; settings glyphs: ${g} rendered`)
