// Renders the details screen's glyphs and the rating source logos to WebP, since the renderer
// can't draw SVG on the older TVs. Glyphs come from the detail, rating and item menu maps in
// scripts/iconPaths.mjs, at the view box that centers each one, into public/icons/d as
// white 96 px squares the renderer tints. Logos come from the Moonfin plugin's assets (see MOONFIN_PLUGIN_ASSETS)
// into public/icons/ratings at 64 px tall, and src/ui/components/details/ratingLogos.js records their widths at 32 px tall.
// Run it with node scripts/detailIcons.mjs after a path or logo changes.
import { writeFileSync, mkdirSync } from 'node:fs'
import { execFileSync } from 'node:child_process'
import { DETAIL as detail, MATERIAL_SYMBOLS as material, MENU as menu, RATING as rating, RT_FALLBACK } from './iconPaths.mjs'

const ASSETS = process.env.MOONFIN_PLUGIN_ASSETS
if (!ASSETS) {
  console.error("Set MOONFIN_PLUGIN_ASSETS to the Moonfin plugin's assets folder, such as Jellyfin/backend/assets in its repo.")
  process.exit(1)
}

// The view box offsets that center these glyphs, keyed by name here.
const OFF_CENTRE = {
  playlist: [20, 40], collection: [20, 20], manageRequests: [0, -21.5], restart: [0, -20], artwork: [0, -20],
  reportIssue: [0, -20], thumbUp: [20, -40], thumbDown: [-20, 40], star: [0, -20], starHalf: [0, -20], starFull: [0, -20],
}

const glyphs = { ...detail }
for (const k of Object.keys(rating)) glyphs[`rating_${k}`] = rating[k]
for (const k of Object.keys(menu)) glyphs[`menu_${k}`] = menu[k]
for (const k of ['lock', 'check', 'close', 'add', 'remove', 'search', 'expand_more', 'arrow_upward', 'arrow_downward']) {
  if (material[k]) glyphs[`m_${k}`] = material[k]
}

// The track picker's picked and unpicked marks, drawn on a 24 grid.
const GRID24 = {
  radio_on: 'M12 2a10 10 0 1 0 0 20 10 10 0 0 0 0-20m-1.4 14.6L6.4 12.4l1.4-1.4 2.8 2.8 5.6-5.6 1.4 1.4z',
  radio_off: 'M12 4a8 8 0 1 1 0 16 8 8 0 0 1 0-16m0-2a10 10 0 1 0 0 20 10 10 0 0 0 0-20',
}

const out = new URL('../public/icons/d/', import.meta.url)
mkdirSync(out, { recursive: true })
let n = 0
for (const [name, d] of Object.entries(glyphs)) {
  const key = name.replace(/^rating_/, '')
  const [dx, dy] = OFF_CENTRE[key] || [0, 0]
  const svg = `<svg xmlns="http://www.w3.org/2000/svg" width="96" height="96" viewBox="${dx} ${dy - 960} 960 960"><path fill="#ffffff" d="${d}"/></svg>`
  const image = execFileSync('magick', ['-background', 'none', '-density', '96', 'svg:-', '-resize', '96x96', '-define', 'webp:lossless=true', '-define', 'webp:exact=true', '-define', 'webp:method=6', 'webp:-'], { input: svg })
  writeFileSync(new URL(`${name}.webp`, out), image)
  n++
}

for (const [name, d] of Object.entries(GRID24)) {
  const svg = `<svg xmlns="http://www.w3.org/2000/svg" width="96" height="96" viewBox="0 0 24 24"><path fill="#ffffff" d="${d}"/></svg>`
  writeFileSync(new URL(`${name}.webp`, out), execFileSync('magick', ['-background', 'none', '-density', '384', 'svg:-', '-resize', '96x96', '-define', 'webp:lossless=true', '-define', 'webp:exact=true', '-define', 'webp:method=6', 'webp:-'], { input: svg }))
  n++
}

const logos = new URL('../public/icons/ratings/', import.meta.url)
mkdirSync(logos, { recursive: true })
const widths = {}
const files = ['imdb', 'tmdb', 'trakt', 'rt-fresh', 'rt-rotten', 'rt-certified', 'rt-verified', 'rt-audience-up', 'rt-audience-down',
  'metacritic', 'metacritic-score', 'metacritic-user', 'letterboxd', 'rogerebert', 'mal', 'anilist']
for (const f of files) {
  const image = execFileSync('magick', ['-background', 'none', '-density', '600', `${ASSETS}/${f}.svg`, '-resize', 'x64', '-define', 'webp:lossless=true', '-define', 'webp:exact=true', '-define', 'webp:method=6', 'webp:-'])
  writeFileSync(new URL(`${f}.webp`, logos), image)
  const size = execFileSync('magick', ['identify', '-format', '%w %h', 'webp:-'], { input: image }).toString().split(' ').map(Number)
  widths[f] = Math.round((size[0] / size[1]) * 32 * 100) / 100
}
// The fallback tomatoes for the server's critic score.
for (const [name, svg] of [['rt-fallback-fresh', RT_FALLBACK.fresh], ['rt-fallback-rotten', RT_FALLBACK.rotten]]) {
  const image = execFileSync('magick', ['-background', 'none', '-density', '600', 'svg:-', '-resize', 'x64', '-define', 'webp:lossless=true', '-define', 'webp:exact=true', '-define', 'webp:method=6', 'webp:-'], { input: svg })
  writeFileSync(new URL(`${name}.webp`, logos), image)
  const size = execFileSync('magick', ['identify', '-format', '%w %h', 'webp:-'], { input: image }).toString().split(' ').map(Number)
  widths[name] = Math.round((size[0] / size[1]) * 32 * 100) / 100
}
writeFileSync(
  new URL('../src/ui/components/details/ratingLogos.js', import.meta.url),
  `// Generated by scripts/detailIcons.mjs: each rating logo's width when drawn 32 px tall.\nexport const LOGO_WIDTHS = ${JSON.stringify(widths, null, 2)}\n`,
)
console.log(`rendered ${n} glyphs and ${Object.keys(widths).length} logos`)
